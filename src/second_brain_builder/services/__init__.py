"""Use cases that the HTTP API, the MCP server, and the worker share.

Build one ``AppContext`` from ``Settings`` and pass it as the first argument of
every function. Functions raise the ``ServiceError`` subclasses in
``services.errors``; the API maps them to HTTP status codes and the MCP server to
tool errors. Inputs and outputs are the Pydantic models in ``services.models``.

The use cases read Brain clones and the database, stage uploads, and enqueue
jobs. They never write to a clone: the worker does every write. The one exception
is ``disconnect_brain``, which removes the whole clone of the Brain.
"""

